/* SIEMPRE arranca en español, a pedido del usuario. El cambio a inglés
   dura lo que dure la visita: no se guarda ni se hereda en la próxima. */
let currentLang = 'es';

export function t(key) {
  return (STRINGS[currentLang] || STRINGS.es)[key] || (STRINGS.es)[key] || key;
}

export function getLang() {
  return currentLang;
}

/* Campo de un dato del menú en el idioma actual: los productos y las
   categorías guardan la traducción como <campo>En (nameEn,
   descriptionEn). En inglés usa esa versión si existe; si falta, cae al
   español en vez de dejar el texto vacío. */
export function campoIdioma(obj, campo) {
  if (!obj) return '';
  if (currentLang === 'en') {
    const en = obj[campo + 'En'];
    if (typeof en === 'string' && en.trim()) return en;
  }
  return obj[campo] || '';
}

export function setLang(lang) {
  if (lang !== 'es' && lang !== 'en') return;
  currentLang = lang;
  // Emit custom event so the UI knows to update
  window.dispatchEvent(new CustomEvent('rz-lang-changed'));
}

// Attach globally for inline HTML event handlers (e.g. onclick="window.setLang('en')")
window.setLang = setLang;
window.getLang = getLang;
window.t = t;
